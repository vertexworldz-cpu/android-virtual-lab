"""Evaluation: held-out loss/perplexity and exact-match task accuracy."""

from __future__ import annotations

import math
from collections import defaultdict

import torch

from .inference import GenerationParams, Generator


@torch.no_grad()
def estimate_loss(model, dataset, batch_size: int, batches: int, device: str) -> dict[str, float]:
    was_training = model.training
    model.eval()
    out = {}
    for split in ("train", "val"):
        total = 0.0
        for _ in range(batches):
            x, y = dataset.get_batch(split, batch_size, device)
            _, loss = model(x, y)
            total += loss.item()
        out[split] = total / batches
    if was_training:
        model.train()
    return out


def perplexity(loss: float) -> float:
    return math.exp(min(loss, 20.0))


def exact_match(generator: Generator, examples: list[dict], limit: int | None = None) -> dict:
    """Greedy-decode each held-out example and compare with the reference answer.

    Returns overall and per-task accuracy plus a sample of failures. This is a
    real measurement: every counted answer was generated by the model."""
    per_task: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    failures = []
    subset = examples[:limit] if limit else examples
    params = GenerationParams(max_new_tokens=64, temperature=0.0)
    for ex in subset:
        prompt, reference = ex["messages"][:-1], ex["messages"][-1]["content"]
        got = generator.complete(prompt, params)
        ok = got.strip() == reference.strip()
        task = ex.get("task", "all")
        per_task[task][0] += int(ok)
        per_task[task][1] += 1
        if not ok and len(failures) < 10:
            failures.append({"prompt": prompt[-1]["content"], "expected": reference, "got": got})
    correct = sum(c for c, _ in per_task.values())
    total = sum(t for _, t in per_task.values())
    return {
        "accuracy": correct / total if total else 0.0,
        "correct": correct,
        "total": total,
        "per_task": {t: {"accuracy": c / n, "correct": c, "total": n} for t, (c, n) in sorted(per_task.items())},
        "failures": failures,
    }
